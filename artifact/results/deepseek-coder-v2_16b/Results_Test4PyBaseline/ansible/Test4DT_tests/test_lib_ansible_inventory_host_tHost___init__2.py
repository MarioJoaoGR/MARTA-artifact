
import pytest
from ansible.inventory.host import Host

# Test initialization with default values
def test_init_default():
    host = Host(name='example_host')
    assert host.name == 'example_host'
    assert host.address == 'example_host'
    assert 'ansible_port' not in host.vars
    assert host._uuid is not None  # UUID should be generated by default

# Test initialization with specified port
def test_init_with_port():
    host = Host(name='example_host', port=22)
    assert host.name == 'example_host'
    assert host.address == 'example_host'
    assert host.vars['ansible_port'] == 22
    assert host._uuid is not None  # UUID should be generated by default

# Test initialization without UUID generation
def test_init_without_uuid():
    host = Host(name='example_host', port=22, gen_uuid=False)
    assert host.name == 'example_host'
    assert host.address == 'example_host'
    assert host.vars['ansible_port'] == 22
    assert host._uuid is None  # UUID should not be generated if gen_uuid is False

# Test setting a variable on the host
def test_set_variable():
    host = Host(name='example_host', port=22)
    host.set_variable('ansible_user', 'admin')
    assert host.vars['ansible_user'] == 'admin'

# Test setting a variable that already exists, updating it recursively if necessary
def test_set_existing_variable():
    host = Host(name='example_host', port=22)
    host.set_variable('ansible_user', {'nested': 'value'})
    assert host.vars['ansible_user'] == {'nested': 'value'}
    host.set_variable('ansible_user', 'admin')
    assert host.vars['ansible_user'] == 'admin'  # The nested structure should be preserved

# Test comparing two hosts with different UUIDs but same name and port
def test_host_comparison():
    host1 = Host('example_host', port=22)
    host2 = Host('another.com', port=22, gen_uuid=False)
    assert host1 != host2  # Different UUIDs should make the hosts not equal
